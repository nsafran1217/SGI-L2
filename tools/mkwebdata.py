#!/usr/bin/env python3
"""The web l2gui's drawing data, taken from SGI's l2gui binary.

    tools/mkwebdata.py ../ist/ist-software-extracted/IST/snxsc_l3/stand/sysco/bin/l2gui \\
        > sys_ctrl/l3/webgui/fldata.js

The original draws with FLTK 1.0 (FLNX) on Nano-X: its colormap (fl_cmap),
the gray ramps of its box types (active_ramp, inactive_ramp), the one font
it ever drew with, Nano-X's "System" (font_winFreeSansSerif11x13), and the
256-colour palette Nano-X maps every colour to (mwstdpal8), and the cosine
table its arcs are computed with (devarc.c) are copied from the binary's data so the web version draws the same pixels.
Needs pyelftools.
"""
import struct
import sys

from elftools.elf.elffile import ELFFile


def main():
    f = open(sys.argv[1], "rb")
    elf = ELFFile(f)
    syms = {s.name: s["st_value"] for s in elf.get_section_by_name(".symtab").iter_symbols()}

    def read(addr, n):
        for s in elf.iter_sections():
            a = s["sh_addr"]
            if a and a <= addr < a + s["sh_size"] and s["sh_type"] != "SHT_NOBITS":
                f.seek(s["sh_offset"] + addr - a)
                return f.read(n)
        raise SystemExit(f"no data at {addr:#x}")

    cmap = [w >> 8 for w in struct.unpack("<256I", read(syms["fl_cmap"], 1024))]
    active = list(read(syms["active_ramp"], 24))
    inactive = list(read(syms["inactive_ramp"], 24))
    (_, maxwidth, height, ascent, first, size, bits, offset,
     width) = struct.unpack("<9I", read(syms["font_winFreeSansSerif11x13"], 36))
    if offset != 0:
        raise SystemExit("the font has an offset table: not handled")
    stride = height * ((maxwidth + 15) // 16)
    glyphs = struct.unpack(f"<{size * stride}H", read(bits, 2 * size * stride))
    widths = list(read(width, size))
    pal = read(syms["mwstdpal8"], 1024)
    palette = [pal[i] << 16 | pal[i + 1] << 8 | pal[i + 2] for i in range(0, 1024, 4)]
    cosine = struct.unpack("<182f", read(syms["cosine"], 728))

    def nums(v, fmt, per):
        return ",\n".join("  " + ", ".join(fmt % x for x in v[i:i + per]) for i in range(0, len(v), per))

    print(f"""// Generated by tools/mkwebdata.py from SGI's l2gui binary: do not edit.
//
// FLTK 1.0's colormap and box gray ramps (LGPL, (c) Bill Spitzak and others)
// and Nano-X's "System" font, winFreeSansSerif11x13 ("Distributed under the
// MPL (c) 1999 darran@rimron.co.uk v0.3 Free Sans Serif"), and its 8-bit
// palette and arc cosine table (Microwindows, (c) Greg Haerr and Eero
// Tamminen), as l2gui has them.

// Fl_Color index -> 0xRRGGBB
export const cmap = [
{nums(cmap, "0x%06x", 8)}
];

// Nano-X's palette (0xRRGGBB): every colour drawn is the nearest of these
export const palette = [
{nums(palette, "0x%06x", 8)}
];

// Nano-X's qcos()/qsin() table: cos(n degrees) and the step to n + 1 (floats)
export const cosine = [
{nums(cosine, "%.9g", 6)}
];

// box-frame letters 'A'..'X' -> Fl_Color, active and inactive widgets
export const activeRamp = [{", ".join(map(str, active))}];
export const inactiveRamp = [{", ".join(map(str, inactive))}];

// a glyph: {stride} rows of 16 bits, leftmost pixel in the top bit
export const font = {{
  height: {height},
  ascent: {ascent},
  first: {first},
  stride: {stride},
  widths: [
{nums(widths, "%d", 16)}
  ],
  bits: [
{nums(glyphs, "0x%04x", 13)}
  ],
}};""")


if __name__ == "__main__":
    main()
